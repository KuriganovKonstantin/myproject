import pandas as pd

from bisect import bisect_left, bisect_right
from time import perf_counter


def hhmm_to_minutes(value):
    """2359 → 23 * 60 + 59 = 1439 минут от начала суток."""
    return (int(value) // 100) * 60 + int(value) % 100


class SegmentTreeIndex:
    """Индекс: рейсы в порядке суточного расписания, значение — задержка вылета."""

    def __init__(self, frame, value_field="DEPARTURE_DELAY"):
        # порядок по времени вылета; FLIGHT_NUMBER — чтобы сортировка была устойчивой
        self.frame = frame.sort_values(
            ["SCHEDULED_DEPARTURE", "FLIGHT_NUMBER"]
        ).reset_index(drop=True)

        # пропуски (отменённые рейсы) считаем нулевой задержкой
        self.values = (
            self.frame[value_field].fillna(0).astype(int).tolist()
        )

        # те же значения в минутах от начала суток — для запросов по времени
        self.minutes = [hhmm_to_minutes(v) for v in self.frame["SCHEDULED_DEPARTURE"]]

        self.tree = SegmentTree(self.values)

    def query(self, l, r):
        """Сумма задержек на позициях [l..r]."""
        return self.tree.query(l, r)

    def update(self, pos, value):
        """Уточнили задержку рейса на позиции pos."""
        self.values[pos] = value
        self.tree.update(pos, value)

    def query_time(self, start_hhmm, end_hhmm):
        """Сумма задержек за окно времени, например query_time(900, 1200)."""
        lo = bisect_left(self.minutes, hhmm_to_minutes(start_hhmm))
        hi = bisect_right(self.minutes, hhmm_to_minutes(end_hhmm)) - 1

        if lo > hi:
            return 0

        return self.tree.query(lo, hi)


def naive_sum(values, l, r):
    """Обычный проход по диапазону."""
    total = 0
    for i in range(l, r + 1):
        total += values[i]
    return total


def make_ops(n, count=2000, window=(1000, 20_000), seed=1):
    """Смешанная нагрузка: половина update, половина query."""
    random.seed(seed)
    ops = []

    for i in range(count):
        if i % 2 == 0:
            ops.append(("update", random.randrange(n), random.randint(0, 300)))

def check_2(x, data, min_share):
    """
    Пользователь активен, если его средняя сессия не короче x минут.
    Проверяем, что активных не меньше min_share от всех.
    """
    active = np.count_nonzero(data >= x)
    return active >= min_share * len(data)

def solve_2(data, min_share):
    """
    Бинарный поиск: максимальный целый порог, при котором активных >= min_share.
    Ищем последний True на отрезке [L, R].
    """
    left = 0                              # при 0 активны все
    right = int(math.ceil(data.max()))    # при таком пороге активных ноль

    while left < right:
        mid = (left + right + 1) // 2     # верхняя половина, т.к. ищем последний True
        if check_2(mid, data, min_share):
            left = mid
        else:
            right = mid - 1

    return left


def check_1(x, data, k):
    """
    Можно ли разложить поток на не более чем k непрерывных блоков,
    у которых сумма в каждом блоке не больше x.

    Жадность: набираем блок, пока очередная сессия влезает.
    Если очередная не влезает — начинаем новый блок.
    Для задачи «минимизировать максимум» жадность оптимальна.
    """
    csum = np.cumsum(data)          # префиксные суммы: сумма блока считается за O(1)
    n = len(csum)

    pos = 0                          # с какого индекса начинается текущий блок
    blocks = 0
    base = 0                         # csum[pos - 1], для pos = 0 это ноль

    while pos < n:
        blocks += 1
        if blocks > k:               # уже больше k блоков — x мал
            return False

        limit = base + x
        # последний индекс, у которого csum <= limit: докуда дотягивается блок
        j = int(np.searchsorted(csum, limit, side="right"))
        if j <= pos:                 # одна сессия не влезает в блок
            return False

        base = csum[j - 1]
        pos = j

    return True

def solve_1(data, k):
    """
    Бинарный поиск по ответу: минимальная пиковая ёмкость блока.
    Ищем первый True на отрезке [L, R].
    """
    left = int(data.max())           # весь блок из одной максимальной сессии
    right = int(np.cumsum(data)[-1]) # сумма всех сессий — влезает в один блок

    while left < right:
        mid = (left + right) // 2
        if check_1(mid, data, k):
            right = mid              # mid подходит, пробуем меньше
        else:
            left = mid + 1           # mid мало

    return left

